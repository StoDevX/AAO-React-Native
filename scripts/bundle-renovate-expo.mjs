#!/usr/bin/env node
/**
 * Write Renovate a version ceiling for every package the installed Expo SDK
 * pins.
 *
 * Renovate has no idea what Expo recommends -- it has no Expo datasource and
 * does not read `bundledNativeModules.json` -- so it only ever offers the
 * newest release. Left alone it walks these packages past the range this SDK
 * was built and tested against, and `validate-expo-versions` then fails the
 * pull request that did it. `allowedVersions` stops the offer being made:
 * Renovate still proposes upgrades, but only inside the SDK's range.
 *
 * Generated rather than written by hand, because the ranges change with every
 * SDK bump and a stale ceiling is worse than none -- it silently pins a
 * package to a version the SDK no longer wants.
 *
 * This is deliberately not a scheduled job. The source is
 * `expo/bundledNativeModules.json`, which ships inside the installed `expo`,
 * so the output can only change when `package.json` does. Regenerating on a
 * timer would produce a pull request nobody asked for; regenerating here means
 * the ceilings move in the same commit as the SDK. `bundle-data` and
 * `bundled.json` already work this way, and CI checks both the same way, with
 * `git diff --exit-code`.
 */

import fs from 'node:fs'
import path from 'node:path'
import {REPO_ROOT} from './paths.mjs'
import {EXPECTED_DEVIATIONS} from './validate-expo-versions.mjs'

/** How a generated rule announces itself, so regenerating can replace them. */
export const GENERATED_MARKER = 'generated by bundle-renovate-expo; the Expo SDK pins'

const byName = (a, b) => a.localeCompare(b)

/**
 * One rule per range the SDK asks for, naming every package that shares it.
 *
 * Packages sharing a range share a rule because Renovate matches on a list,
 * and eighteen rules read better than twenty-five saying the same thing.
 *
 * A package in `deviations` gets no ceiling. We hold those deliberately off
 * the SDK's range, so capping them at it would leave Renovate unable to offer
 * any release we would actually take -- @sentry/react-native held to ~7.11.0
 * while the app runs 8.x means no Sentry update ever again.
 */
export function buildAllowedVersionRules(recommended, declared, deviations) {
	let byRange = new Map()

	for (let name of [...declared].sort(byName)) {
		let range = recommended[name]
		if (!range || deviations.has(name)) continue

		if (!byRange.has(range)) byRange.set(range, [])
		byRange.get(range).push(name)
	}

	return [...byRange]
		.map(([allowedVersions, matchPackageNames]) => ({
			description: `${GENERATED_MARKER} ${matchPackageNames.join(', ')}`,
			matchPackageNames,
			allowedVersions,
		}))
		.sort((a, b) => byName(a.matchPackageNames[0], b.matchPackageNames[0]))
}

/**
 * The rule list with this run's generated rules in place of the last run's.
 *
 * Generated rules go first so that a hand-written rule after them still wins
 * on any field they share -- Renovate lets a later rule override an earlier
 * one, and the hand-written ones are the deliberate exceptions.
 */
export function withGeneratedRules(rules, generated) {
	return [...generated, ...rules.filter((rule) => !rule.description?.startsWith(GENERATED_MARKER))]
}

function main() {
	let configPath = path.join(REPO_ROOT, 'renovate.json')
	let config = JSON.parse(fs.readFileSync(configPath, 'utf-8'))

	let recommended = JSON.parse(
		fs.readFileSync(
			path.join(REPO_ROOT, 'node_modules', 'expo', 'bundledNativeModules.json'),
			'utf-8',
		),
	)
	let manifest = JSON.parse(fs.readFileSync(path.join(REPO_ROOT, 'package.json'), 'utf-8'))
	let declared = Object.keys({...manifest.dependencies, ...manifest.devDependencies})

	let generated = buildAllowedVersionRules(recommended, declared, EXPECTED_DEVIATIONS)
	config.packageRules = withGeneratedRules(config.packageRules ?? [], generated)

	fs.writeFileSync(configPath, `${JSON.stringify(config, null, 2)}\n`)
	let capped = new Set(generated.flatMap((rule) => rule.matchPackageNames))
	console.log(
		`bundle-renovate-expo: ${generated.length} ceilings over ${capped.size} packages -> renovate.json`,
	)
}

// The guard matters more here than in a validator: without it, importing this
// module from its own test rewrites renovate.json.
if (import.meta.main) {
	main()
}
