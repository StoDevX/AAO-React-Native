#!/usr/bin/env node
/**
 * Writes `symbol-assets.ts`, the table of Material Symbols `symbol-table.ts`
 * names, as the assets Metro bundles for each: `[outlined, filled]`.
 *
 * The outlined icons come from `@expo/material-symbols`, the source Expo
 * recommends for Android icons: each is an import of its own subpath
 * (`@expo/material-symbols/star.xml`), so Metro bundles only those the table
 * names. That package ships outlined icons only; the filled variant a `.fill`
 * SF Symbol draws is downloaded into `symbols/` by the package's own CLI
 * (`add-material-symbols --fill`), from the same Google Fonts release.
 *
 * Run it again after adding a symbol to `symbol-table.ts`:
 *
 *     node source/android-ui/sync-symbols.mjs
 */
import {execFileSync} from 'node:child_process'
import fs from 'node:fs/promises'
import {createRequire} from 'node:module'
import path from 'node:path'
import {fileURLToPath} from 'node:url'

import {FALLBACK_SYMBOL, SF_TO_MATERIAL} from './symbol-table.ts'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const FILLED_DIR = path.join(HERE, 'symbols')
const require = createRequire(import.meta.url)
// The package exports only its icons, so it is found through one of them.
const PACKAGE_DIR = path.dirname(path.dirname(require.resolve('@expo/material-symbols/star.xml')))
const CLI = path.join(PACKAGE_DIR, 'bin', 'add-material-symbols.mjs')

let names = [...new Set([...Object.values(SF_TO_MATERIAL), FALLBACK_SYMBOL])].sort()

// Every name must be one the package ships: Google renames symbols, and a
// retired name would only fail when Metro could not resolve its import.
let shipped = await Promise.all(
	names.map((name) =>
		fs.access(path.join(PACKAGE_DIR, 'icons', `${name}.xml`)).then(
			() => true,
			() => false,
		),
	),
)
let missing = names.filter((_, index) => !shipped[index])
if (missing.length > 0) {
	console.error(`@expo/material-symbols has no icon named: ${missing.join(', ')}`)
	process.exit(1)
}

// The filled variants, fetched afresh so a removed symbol's file goes too.
await fs.rm(FILLED_DIR, {recursive: true, force: true})
await fs.mkdir(FILLED_DIR, {recursive: true})
execFileSync(process.execPath, [CLI, '--fill', '--output', FILLED_DIR, ...names], {
	stdio: 'inherit',
})

/**
 * A Material Symbol's name as the stem of a JavaScript identifier: `open_in_new`
 * → `openInNew`. A suffix always follows it, so `delete` or `public` stays legal.
 */
let identifier = (name) => name.replaceAll(/_([a-z0-9])/gu, (_, letter) => letter.toUpperCase())

let imports = names.flatMap((name) => [
	`import ${identifier(name)}Outlined from '@expo/material-symbols/${name}.xml'`,
	`import ${identifier(name)}Filled from './symbols/${name}_fill.xml'`,
])
let rows = names.map(
	(name) => `\t${name}: [${identifier(name)}Outlined, ${identifier(name)}Filled],`,
)
let source = `/**
 * Generated by \`sync-symbols.mjs\` -- do not edit by hand.
 *
 * Each Material Symbol \`symbol-table.ts\` names, as the assets Metro bundles
 * for it: \`[outlined, filled]\`. The outlined icons are
 * \`@expo/material-symbols\`'; the filled ones, which it does not ship, are
 * in \`symbols/\`. Metro bundles only a file an import names, which is why
 * this is a table of imports and not a template.
 */
import type {ImageRequireSource} from 'react-native'

${imports.join('\n')}

export const SYMBOL_ASSETS: Readonly<Record<string, readonly [ImageRequireSource, ImageRequireSource]>> = {
${rows.join('\n')}
}
`
await fs.writeFile(path.join(HERE, 'symbol-assets.ts'), source)
console.log(`Wrote ${names.length} symbols`)
