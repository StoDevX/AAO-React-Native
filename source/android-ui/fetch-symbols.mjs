#!/usr/bin/env node
/**
 * Downloads the Material Symbols that `symbol-table.ts` maps the app's SF
 * Symbols to, as Android vector drawables, into `symbols/`, and writes
 * `symbol-assets.ts`, the static `require()` map Metro bundles them through.
 *
 * Metro only bundles a file a literal `require()` names, so the map has to be
 * generated: run this again after adding a symbol to the table.
 *
 *     node source/android-ui/fetch-symbols.mjs
 *
 * The drawables come from google/material-design-icons, the Outlined style at
 * 24dp, with the FILL 1 variant beside each. Expo UI's `Icon` parses them with
 * Compose's PathParser; `@expo/ui/jetpack-compose` patches the asset resolver
 * so Metro serves `.xml` assets in development too.
 */
import fs from 'node:fs/promises'
import path from 'node:path'
import {fileURLToPath} from 'node:url'

import {FALLBACK_SYMBOL, SF_TO_MATERIAL} from './symbol-table.ts'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const OUT_DIR = path.join(HERE, 'symbols')
const BASE = 'https://raw.githubusercontent.com/google/material-design-icons/master/symbols/android'

/** Fetches one drawable, or null when the repository has no such file. */
async function download(name, variant) {
	let suffix = variant === 'fill' ? '_fill1_24px.xml' : '_24px.xml'
	let response = await fetch(`${BASE}/${name}/materialsymbolsoutlined/${name}${suffix}`)
	if (response.status === 404) {
		return null
	}
	if (!response.ok) {
		throw new Error(`${name} (${variant}): HTTP ${response.status}`)
	}
	return response.text()
}

let names = [...new Set([...Object.values(SF_TO_MATERIAL), FALLBACK_SYMBOL])].sort()
await fs.mkdir(OUT_DIR, {recursive: true})

let missing = []
let entries = []
for (let name of names) {
	let [outlined, filled] = await Promise.all([download(name, 'outlined'), download(name, 'fill')])
	if (!outlined) {
		missing.push(name)
		continue
	}
	await fs.writeFile(path.join(OUT_DIR, `${name}.xml`), outlined)
	// A symbol with no filled variant draws the same either way.
	await fs.writeFile(path.join(OUT_DIR, `${name}_fill.xml`), filled ?? outlined)
	entries.push(name)
}

if (missing.length > 0) {
	console.error(`No Material Symbol named: ${missing.join(', ')}`)
	process.exitCode = 1
}

let lines = entries.map(
	(name) =>
		`\t${name}: [require('./symbols/${name}.xml'), require('./symbols/${name}_fill.xml')],`,
)
let source = `/**
 * Generated by \`fetch-symbols.mjs\` -- do not edit by hand.
 *
 * Each Material Symbol \`symbol-table.ts\` names, as the asset Metro bundles
 * for it: \`[outlined, filled]\`. Metro only bundles a file a literal
 * \`require()\` names, which is why this is a table and not a template.
 */
import type {ImageSourcePropType} from 'react-native'

export const SYMBOL_ASSETS: Readonly<Record<string, readonly [ImageSourcePropType, ImageSourcePropType]>> = {
${lines.join('\n')}
}
`
await fs.writeFile(path.join(HERE, 'symbol-assets.ts'), source)
console.log(`Wrote ${entries.length} symbols`)
