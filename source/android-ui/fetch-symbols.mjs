#!/usr/bin/env node
/**
 * Downloads the Material Symbols that `symbol-table.ts` maps the app's SF
 * Symbols to, as Android vector drawables, into `symbols/`, and writes
 * `symbol-assets.ts`, the table of imports Metro bundles them through.
 *
 * Metro bundles only a file an import names, so the table has to be generated:
 * run this again after adding a symbol to `symbol-table.ts`.
 *
 *     node source/android-ui/fetch-symbols.mjs
 *
 * The drawables come from google/material-design-icons, the Outlined style at
 * 24dp, with the FILL 1 variant beside each. Expo UI's `Icon` parses them with
 * Compose's PathParser; `@expo/ui/jetpack-compose` patches the asset resolver
 * so Metro serves `.xml` assets in development too.
 */
import fs from 'node:fs/promises'
import path from 'node:path'
import {fileURLToPath} from 'node:url'

import {FALLBACK_SYMBOL, SF_TO_MATERIAL} from './symbol-table.ts'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const OUT_DIR = path.join(HERE, 'symbols')
const BASE = 'https://raw.githubusercontent.com/google/material-design-icons/master/symbols/android'

/** Fetches one drawable, or null when the repository has no such file. */
async function download(name, variant) {
	let suffix = variant === 'fill' ? '_fill1_24px.xml' : '_24px.xml'
	let response = await fetch(`${BASE}/${name}/materialsymbolsoutlined/${name}${suffix}`)
	if (response.status === 404) {
		return null
	}
	if (!response.ok) {
		throw new Error(`${name} (${variant}): HTTP ${response.status}`)
	}
	return response.text()
}

let names = [...new Set([...Object.values(SF_TO_MATERIAL), FALLBACK_SYMBOL])].sort()
await fs.mkdir(OUT_DIR, {recursive: true})

let results = await Promise.all(
	names.map(async (name) => {
		let [outlined, filled] = await Promise.all([download(name, 'outlined'), download(name, 'fill')])
		if (!outlined) {
			return {name, found: false}
		}
		await fs.writeFile(path.join(OUT_DIR, `${name}.xml`), outlined)
		// A symbol with no filled variant draws the same either way.
		await fs.writeFile(path.join(OUT_DIR, `${name}_fill.xml`), filled ?? outlined)
		return {name, found: true}
	}),
)
let missing = results.filter((result) => !result.found).map((result) => result.name)
let entries = results.filter((result) => result.found).map((result) => result.name)

if (missing.length > 0) {
	console.error(`No Material Symbol named: ${missing.join(', ')}`)
	process.exitCode = 1
}

/**
 * A Material Symbol's name as the stem of a JavaScript identifier: `open_in_new`
 * → `openInNew`. A suffix always follows it, so `delete` or `public` stays legal.
 */
let identifier = (name) => name.replaceAll(/_([a-z0-9])/gu, (_, letter) => letter.toUpperCase())

let imports = entries.flatMap((name) => [
	`import ${identifier(name)}Outlined from './symbols/${name}.xml'`,
	`import ${identifier(name)}Filled from './symbols/${name}_fill.xml'`,
])
let rows = entries.map(
	(name) => `\t${name}: [${identifier(name)}Outlined, ${identifier(name)}Filled],`,
)
let source = `/**
 * Generated by \`fetch-symbols.mjs\` -- do not edit by hand.
 *
 * Each Material Symbol \`symbol-table.ts\` names, as the assets Metro bundles
 * for it: \`[outlined, filled]\`. Metro bundles only a file an import names,
 * which is why this is a table of imports and not a template.
 */
import type {ImageRequireSource} from 'react-native'

${imports.join('\n')}

export const SYMBOL_ASSETS: Readonly<Record<string, readonly [ImageRequireSource, ImageRequireSource]>> = {
${rows.join('\n')}
}
`
await fs.writeFile(path.join(HERE, 'symbol-assets.ts'), source)
console.log(`Wrote ${entries.length} symbols`)
